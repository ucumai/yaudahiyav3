// Helper to normalize strings for comparison
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .replace(/[.,\-_/()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Normalizes Kode Rekening by removing all dots, spaces, dashes, leading/trailing zeros formatting
 * so that '5.1.02.03.02.0120', '5.1.02.03.02.01.20', and '510203020120' are treated identically.
 */
export function normalizeKodeRekening(kode: string): string {
  if (!kode) return '';
  return kode.replace(/[.\s\-_/]/g, '').trim();
}

// Check and find match in RKAS items
export function findMatchInRKAS(
  kodeRekening: string,
  uraian: string,
  rkasList: RKASItem[] = rkasFebruaryCatalog
): RKASItem | null {
  const normUraian = normalizeText(uraian);
  const cleanKode = normalizeKodeRekening(kodeRekening);

  if (!normUraian) return null;

  // 1. First Tier: Exact or prefix match on Kode Rekening (e.g. 510203020 matches 510203020120)
  const sameKodeItems = rkasList.filter((item) => {
    if (!cleanKode || !item.kode_rekening) return false;
    const itemClean = normalizeKodeRekening(item.kode_rekening);
    return (
      itemClean === cleanKode ||
      itemClean.startsWith(cleanKode) ||
      cleanKode.startsWith(itemClean) ||
      (cleanKode.length >= 8 && itemClean.startsWith(cleanKode.slice(0, 8)))
    );
  });

  if (sameKodeItems.length > 0) {
    // 1a. Exact text match within same kode
    for (const item of sameKodeItems) {
      const itemNorm = normalizeText(item.uraian);
      if (itemNorm === normUraian) {
        return item;
      }
    }
    // 1b. Substring / keyword match within same kode
    for (const item of sameKodeItems) {
      const itemNorm = normalizeText(item.uraian);
      if (
        normUraian.includes(itemNorm) ||
        itemNorm.includes(normUraian)
      ) {
        return item;
      }
      // Token overlap match
      const tokens1 = normUraian.split(' ').filter((t) => t.length > 2);
      const tokens2 = itemNorm.split(' ').filter((t) => t.length > 2);
      const matchCount = tokens1.filter((t) => tokens2.includes(t)).length;
      if (matchCount >= 2 || (tokens1.length === 1 && matchCount === 1)) {
        return item;
      }
    }
  }

  // 2. Second Tier: Global exact text match across all RKAS items (regardless of kode rekening)
  for (const item of rkasList) {
    const itemNorm = normalizeText(item.uraian);
    if (itemNorm === normUraian) {
      return item;
    }
  }

  // 3. Third Tier: Substring match across all items
  for (const item of rkasList) {
    const itemNorm = normalizeText(item.uraian);
    if (
      normUraian.includes(itemNorm) ||
      itemNorm.includes(normUraian)
    ) {
      return item;
    }
  }

  // 4. Fourth Tier: Significant word overlap
  const uTokens = normUraian.split(' ').filter((t) => t.length > 2);
  let bestItem: RKASItem | null = null;
  let maxMatches = 0;

  for (const item of rkasList) {
    const itemNorm = normalizeText(item.uraian);
    const itemTokens = itemNorm.split(' ').filter((t) => t.length > 2);
    const common = uTokens.filter((t) => itemTokens.includes(t)).length;
    if (common > maxMatches && common >= 1) {
      maxMatches = common;
      bestItem = item;
    }
  }

  return bestItem;
}
